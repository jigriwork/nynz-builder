/** Writes THIRD_PARTY_NOTICES.md from the installed direct runtime dependencies. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const rows: string[] = [];
for (const name of Object.keys(pkg.dependencies).sort()) {
  const dir = join("node_modules", name);
  const meta = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licenseFile = readdirSync(dir).find((file) => /^(licen[cs]e|copying)/i.test(file));
  const copyright = licenseFile ? (readFileSync(join(dir, licenseFile), "utf8").match(/^.*copyright.*$/im)?.[0]?.trim() || "") : "";
  rows.push(`| \`${name}\` | ${meta.version} | ${typeof meta.license === "string" ? meta.license : JSON.stringify(meta.license)} | ${copyright.replace(/\|/g, "/")} |`);
}
const body = `# Third-party notices

NYNZ's web application and worker include the direct runtime dependencies
below (generated by \`pnpm notices\` from installed packages). Each package's
full licence text ships inside that package; MIT and ISC licences require the
copyright and permission notice to accompany copies or substantial portions.
\`jszip\` is dual-licensed (MIT or GPL-3.0-or-later); NYNZ uses it under MIT.

NYNZ itself began from the MIT-licensed \`firecrawl/open-lovable\` project; see
\`LICENSE\` and \`docs/UPSTREAM.md\`. Transitive dependencies, fonts and
generated-app dependencies are not listed here; a full SBOM/licence review is
still required before distributing NYNZ as a package.

Exported customer projects contain only project-authored files and NYNZ's
own starter configuration, so no third-party notice is added to exports.

| Package | Version | Licence | Copyright line |
|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync("THIRD_PARTY_NOTICES.md", body);
console.log(`wrote ${rows.length} entries`);
if (!existsSync("LICENSE")) process.exit(1);
